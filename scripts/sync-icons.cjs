'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const icons = require('../assets/iconoir/ui-icons.json');

function renderSymbols() {
  return Object.entries(icons).map(([name, filename]) => {
    if (!/^[a-z-]+$/.test(name) || !/^[a-z-]+\.svg$/.test(filename)) throw new Error('Invalid icon mapping');
    const source = fs.readFileSync(path.join(root, 'assets/iconoir', filename), 'utf8');
    const match = source.trim().match(/^<svg\b([^>]*)>([\s\S]*)<\/svg>$/);
    if (!match || !match[1].includes('viewBox="0 0 24 24"')) throw new Error(`Invalid Iconoir SVG: ${filename}`);
    const attributes = match[1].replace(/\s(?:width|height|xmlns)="[^"]*"/g, '');
    return `    <symbol id="i-${name}"${attributes}>${match[2].trim().replace(/\n/g, '')}</symbol>`;
  }).join('\n');
}

function syncIcons(write = false) {
  const filename = path.join(root, 'src/client/index.html'), original = fs.readFileSync(filename, 'utf8');
  const updated = original.replace(/(<svg class="icon-definitions"[^>]*>)[\s\S]*?(\s*<\/svg>)/,
    (_, opening) => `${opening}\n    <!-- Iconoir v7.12.2, MIT. Generated by scripts/sync-icons.cjs; see assets/iconoir/LICENSE. -->\n${renderSymbols()}\n  </svg>`);
  if (updated === original) return;
  if (!write) throw new Error('Icon definitions are out of date. Run node scripts/sync-icons.cjs.');
  fs.writeFileSync(filename, updated);
}

if (require.main === module) syncIcons(true);
module.exports = { icons, renderSymbols, syncIcons };
